#Uma lista é uma coleção ordenada e mutável que pode armazenar múltiplos valores de tipos diferentes
#É criada com colchetes [] e acessamos os elementos pelo seu índice.

#Ex: alunos = ['ANNA','BRUNO','CARLOS','DIANA','EDUARDO']
#----------------0--------1----------2----------3

#Os índices em Py começam em 0!
#Índices negativos acessam o final da lista: lista[-1] retorna o último item.

#Criar
alunos = ['Anna', 'Bruno', 'Carlos', 'Diana', 'Eduardo']

#Acessar
print(alunos[0])

#Tamanho da lista
print(len(alunos))

#Fatiar
